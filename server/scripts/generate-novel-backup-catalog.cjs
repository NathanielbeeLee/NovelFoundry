fs.mkdirSync(path.join(root, "schema"), { recursive: true });
for (const [group, names] of Object.entries(groups)) {
  const result = {};
  for (const name of names) {
    if (!models[name]) throw new Error(`Missing model ${name}`);
    const fields = {}, refs = {};
    for (const line of models[name].split("\n")) {
      const match = /^\s*(\w+)\s+(\w+)(\?|\[\])?(.*)/.exec(line);
      if (!match) continue;
      const [,field,type,modifier,tail]=match;
      if (models[type]) {
        const relation=/fields:\s*\[([^\]]+)\]/.exec(tail);
        if(relation) for(const key of relation[1].split(",")) refs[key.trim()]=type;
        continue;
      }
      if(modifier === "[]") throw new Error(`Review scalar list ${name}.${field}`);
      fields[field]={type,...(modifier === "?" ? {nullable:true}:{}),...(/@default|@updatedAt/.test(tail)?{default:true}:{}),...(/@unique/.test(tail)?{unique:true}:{})};
    }
    result[name]={fields,refs};
  }
  const lines = ['// Generated by server/scripts/generate-novel-backup-catalog.cjs.', 'import type { BackupModel } from "../catalogTypes";', `export const ${group}Models: Record<string, BackupModel> = {`];
  for(const [name,spec] of Object.entries(result)) {
    lines.push(`  ${name}: {`, '    fields: {');
    for(const [key,value] of Object.entries(spec.fields)) lines.push(`      ${key}: ${JSON.stringify(value)},`);
    lines.push('    },', '    refs: {');
    for(const [key,value] of Object.entries(spec.refs)) lines.push(`      ${key}: ${JSON.stringify(value)},`);
    lines.push('    },', '  },');
  }
  lines.push('};', '');
  fs.writeFileSync(path.join(root, 'schema', `${group}.ts`), lines.join('\n'));
}
